"""
data/dataset.py
Unified dataset interface supporting Pothole-600 and PotholeRGBD datasets.

Pothole-600 : RGB images + binary segmentation masks (no ground-truth depth)
PotholeRGBD : RGB images + binary segmentation masks + metric depth maps

When ground-truth depth is unavailable, a pseudo-depth map generated by
MiDaS v3 is used (see data/pseudo_depth.py).
"""
from __future__ import annotations

import os
import random
from enum import Enum
from pathlib import Path
from typing import Optional, Tuple

import cv2
import numpy as np
import torch
from omegaconf import DictConfig
from torch.utils.data import Dataset

from data.augmentation import PotholeAugmentor
from data.pseudo_depth import PseudoDepthGenerator


class DatasetMode(str, Enum):
    TRAIN = "train"
    VAL   = "val"
    TEST  = "test"


class PotholeDataset(Dataset):
    """
    Unified dataset class for pothole detection.

    Parameters
    ----------
    dataset_cfg : DictConfig
        Merged dataset configuration (from dataset_config.yaml).
    mode : DatasetMode
        Which split to load.
    pseudo_depth_generator : PseudoDepthGenerator | None
        Pre-initialised MiDaS generator. If None and the dataset has no
        ground-truth depth, a new generator is created lazily.
    """

    def __init__(
        self,
        dataset_cfg: DictConfig,
        mode: DatasetMode = DatasetMode.TRAIN,
        pseudo_depth_generator: Optional[PseudoDepthGenerator] = None,
    ) -> None:
        super().__init__()
        self.cfg = dataset_cfg
        self.mode = mode
        self._pseudo_gen = pseudo_depth_generator

        # Resolve active dataset
        active_key: str = dataset_cfg.datasets.active
        self.ds_cfg = dataset_cfg.datasets[active_key]
        self.has_depth: bool = self.ds_cfg.has_depth

        # Resolve root (supports env-var substitution)
        root_str: str = self.ds_cfg.root
        self.root = Path(os.path.expandvars(root_str))

        # Build file lists
        self._image_paths: list[Path] = []
        self._mask_paths:  list[Path] = []
        self._depth_paths: list[Optional[Path]] = []
        self._collect_files()
        self._split_files()

        # Augmentor
        self.augmentor = PotholeAugmentor(dataset_cfg, train=(mode == DatasetMode.TRAIN))

        # Preprocessing parameters
        self.img_size: Tuple[int, int] = tuple(dataset_cfg.preprocessing.image_size)  # (H, W)
        self.mean = np.array(dataset_cfg.preprocessing.normalize.mean, dtype=np.float32)
        self.std  = np.array(dataset_cfg.preprocessing.normalize.std,  dtype=np.float32)

    # ------------------------------------------------------------------
    # File collection helpers
    # ------------------------------------------------------------------

    def _collect_files(self) -> None:
        """Walk dataset root and collect image/mask/depth file paths."""
        img_dir   = self.root / self.ds_cfg.image_dir
        mask_dir  = self.root / self.ds_cfg.mask_dir
        depth_dir = self.root / self.ds_cfg.depth_dir if self.has_depth else None

        if not img_dir.exists():
            raise FileNotFoundError(
                f"Image directory not found: {img_dir}\n"
                f"Set the environment variable or update dataset_config.yaml."
            )

        exts = {".jpg", ".jpeg", ".png", ".bmp"}
        img_files = sorted(p for p in img_dir.iterdir() if p.suffix.lower() in exts)

        for img_path in img_files:
            # Find matching mask
            mask_path = self._find_counterpart(mask_dir, img_path)
            if mask_path is None:
                continue  # skip unpaired images

            # Find depth (optional)
            depth_path: Optional[Path] = None
            if self.has_depth and depth_dir is not None:
                depth_path = self._find_counterpart(depth_dir, img_path)

            self._image_paths.append(img_path)
            self._mask_paths.append(mask_path)
            self._depth_paths.append(depth_path)

    @staticmethod
    def _find_counterpart(directory: Path, ref: Path) -> Optional[Path]:
        """Return the file in *directory* whose stem matches *ref* (any extension)."""
        for ext in [".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"]:
            candidate = directory / (ref.stem + ext)
            if candidate.exists():
                return candidate
        return None

    def _split_files(self) -> None:
        """Apply train/val/test split using configured ratios."""
        n = len(self._image_paths)
        if n == 0:
            return  # empty — unit-test safe

        split_cfg = self.cfg.splits
        seed = int(split_cfg.seed)
        rng = random.Random(seed)

        indices = list(range(n))
        rng.shuffle(indices)

        train_end = int(n * split_cfg.train)
        val_end   = train_end + int(n * split_cfg.val)

        split_map = {
            DatasetMode.TRAIN: indices[:train_end],
            DatasetMode.VAL:   indices[train_end:val_end],
            DatasetMode.TEST:  indices[val_end:],
        }
        chosen = split_map[self.mode]

        self._image_paths = [self._image_paths[i] for i in chosen]
        self._mask_paths  = [self._mask_paths[i]  for i in chosen]
        self._depth_paths = [self._depth_paths[i] for i in chosen]

    # ------------------------------------------------------------------
    # Dataset protocol
    # ------------------------------------------------------------------

    def __len__(self) -> int:
        return len(self._image_paths)

    def __getitem__(self, idx: int) -> dict:
        img_path   = self._image_paths[idx]
        mask_path  = self._mask_paths[idx]
        depth_path = self._depth_paths[idx]

        # --- Load RGB image ---
        image = cv2.imread(str(img_path), cv2.IMREAD_COLOR)
        if image is None:
            raise IOError(f"Cannot read image: {img_path}")
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # --- Load mask (binary, H×W) ---
        mask = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)
        if mask is None:
            raise IOError(f"Cannot read mask: {mask_path}")
        mask = (mask > 127).astype(np.float32)  # binarise

        # --- Load or generate depth ---
        if depth_path is not None and depth_path.exists():
            depth = cv2.imread(str(depth_path), cv2.IMREAD_UNCHANGED)
            if depth is None:
                depth = self._get_pseudo_depth(image)
            else:
                depth = depth.astype(np.float32) * self.cfg.preprocessing.depth_scale
        else:
            depth = self._get_pseudo_depth(image)

        # --- Resize ---
        h, w = self.img_size
        image = cv2.resize(image, (w, h), interpolation=cv2.INTER_LINEAR)
        mask  = cv2.resize(mask,  (w, h), interpolation=cv2.INTER_NEAREST)
        depth = cv2.resize(depth, (w, h), interpolation=cv2.INTER_LINEAR)

        # --- Augmentation ---
        if self.mode == DatasetMode.TRAIN:
            image, mask, depth = self.augmentor(image, mask, depth)

        # --- Normalise image ---
        image = image.astype(np.float32) / 255.0
        image = (image - self.mean) / self.std

        # --- To tensors ---
        image_t = torch.from_numpy(image.transpose(2, 0, 1)).float()          # (3, H, W)
        mask_t  = torch.from_numpy(mask[np.newaxis]).float()                  # (1, H, W)
        depth_t = torch.from_numpy(depth[np.newaxis]).float()                 # (1, H, W)

        return {
            "image":      image_t,
            "mask":       mask_t,
            "depth":      depth_t,
            "image_path": str(img_path),
            "has_gt_depth": depth_path is not None and depth_path.exists(),
        }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _get_pseudo_depth(self, image_rgb: np.ndarray) -> np.ndarray:
        """Generate pseudo-depth using MiDaS v3 for RGB-only samples."""
        if self._pseudo_gen is None:
            self._pseudo_gen = PseudoDepthGenerator(self.cfg)
        return self._pseudo_gen.infer(image_rgb)
